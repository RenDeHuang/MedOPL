import { createPortalApiPayloads } from "../domain/portal-api-payloads.mjs";
import { createPortalAdminApiRoutes } from "../routes/admin-api.routes.mjs";
import { createPortalApiRoutes } from "../routes/portal-api.routes.mjs";
import { createPortalAdminApiPayloads } from "./portal-admin-api-payloads.mjs";
import {
  groupBillingByDay,
  normalizePageSize,
  paginateRows,
  parsePositiveInt,
  rangeBounds,
  withinDateRange,
} from "./portal-page-payloads.mjs";
import { createPortalSessionTracePayloads } from "./portal-session-trace-payloads.mjs";
import { buildUserBillingSummary } from "../domain/wallet-ledger.mjs";

export function createPortalApiRuntimeHandlers({
  activeUserStatus,
  adminScopeResult,
  announcementRows,
  buildAdminSecuritySummary,
  buildCommercialProfile,
  buildWorkspacePayload,
  collectRunsForTask,
  collectRunsForUser,
  currentServerPlanSelection,
  currentTaskSpaceForUser,
  evaluateUserPolicy,
  fetchBillingStatus,
  fetchBillingSummary,
  fetchHarborImageRows,
  fetchHarborSummary,
  fetchLangfuseSummary,
  fetchMinioSummary,
  fetchOplAdapterCosts,
  fetchOplAdapterRuns,
  fetchOplAdapterTraceRows,
  fetchPendingSummary,
  fetchTraceRows,
  fetchWorkspaceMinioState,
  fetchWorkspaceStorageSnapshot,
  findTaskSpace,
  formatDateTime,
  humanizeStatus,
  isRunTerminal,
  latestActiveWorkspaceSession,
  listTaskSpacesForUser,
  money,
  probe,
  readPortalEvents,
  readSessionsRequestOptions,
  readTracesRequestOptions,
  readWorkspaceSession,
  redisConfigured,
  runtimePerformanceSummary,
  sanitizeTaskTitle,
  sendJson,
  storageMode,
  productProfile,
  portalConfig,
  providerSecretStore,
  readBody,
  urls,
  visibleAnnouncementRows,
  writeDb,
  workspaceChatSessionsForUser,
}) {
  const adminPayloads = createPortalAdminApiPayloads({
    activeUserStatus,
    buildAdminSecuritySummary,
    collectRunsForTask,
    collectRunsForUser,
    fetchBillingStatus,
    fetchBillingSummary,
    fetchHarborSummary,
    fetchLangfuseSummary,
    fetchMinioSummary,
    fetchPendingSummary,
    fetchTraceRows,
    fetchWorkspaceMinioState,
    fetchWorkspaceStorageSnapshot,
    formatDateTime,
    groupBillingByDay,
    humanizeStatus,
    isRunTerminal,
    latestActiveWorkspaceSession,
    listTaskSpacesForUser,
    money,
    normalizePageSize,
    paginateRows,
    probe,
    rangeBounds,
    readPortalEvents,
    readWorkspaceSession,
    redisConfigured,
    runtimePerformanceSummary,
    sanitizeTaskTitle,
    storageMode,
    productProfile,
    urls,
    withinDateRange,
    workspaceChatSessionsForUser,
  });
  const handlePortalAdminApiRoutes = createPortalAdminApiRoutes({
    sendJson,
    ...adminPayloads,
  });

  const {
    buildSessionTraceDetailPayload,
    buildSessionTracesApiPayload,
  } = createPortalSessionTracePayloads({
    fetchTraceRows,
    fetchOplAdapterTraceRows,
    fetchWorkspaceStorageSnapshot,
    fetchBillingSummary,
    findTaskSpace,
    readPortalEvents,
    paginateRows,
    normalizePageSize,
    parsePositiveInt,
  });

  const portalApiPayloads = createPortalApiPayloads({
    buildWorkspacePayload,
    collectRunsForUser,
    fetchBillingSummary,
    fetchHarborSummary,
    fetchLangfuseSummary,
    findTaskSpace,
    isRunTerminal,
    normalizePageSize,
    paginateRows,
  });
  const handlePortalApiRoutes = createPortalApiRoutes({
    activeUserStatus,
    adminScopeResult,
    announcementRows,
    buildCommercialProfile,
    buildSessionTraceDetailPayload,
    buildSessionTracesApiPayload,
    collectRunsForUser,
    currentServerPlanSelection,
    currentTaskSpaceForUser,
    evaluateUserPolicy,
    fetchBillingSummary,
    fetchHarborImageRows,
    fetchHarborSummary,
    fetchLangfuseSummary,
    fetchOplAdapterCosts,
    fetchOplAdapterRuns,
    fetchOplAdapterTraceRows,
    fetchTraceRows,
    formatDateTime,
    isRunTerminal,
    normalizePageSize,
    paginateRows,
    parsePositiveInt,
    productProfile,
    providerSecretStore,
    readBody,
    readSessionsRequestOptions,
    readTracesRequestOptions,
    sendJson,
    buildUserBillingSummary,
    cloudOperationRunnerMode: portalConfig?.PORTAL_CLOUD_OPERATION_RUNNER_MODE,
    cloudOperationRunnerScript: portalConfig?.PORTAL_CLOUD_OPERATION_RUNNER_SCRIPT,
    cloudOperationSecretFile: portalConfig?.PORTAL_CLOUD_OPERATION_PACKAGE_C_SECRET_FILE,
    cloudOperationComputeNodePoolRef: portalConfig?.PORTAL_CLOUD_OPERATION_COMPUTE_NODE_POOL_REF,
    cloudOperationComputePoolBaselineCapacity: portalConfig?.PORTAL_CLOUD_OPERATION_COMPUTE_POOL_BASELINE_CAPACITY,
    enableCloudOperationProductionBridge: portalConfig?.PORTAL_ENABLE_CLOUD_OPERATION_PRODUCTION_BRIDGE,
    enableCloudOperationTestBridge: portalConfig?.PORTAL_ENABLE_CLOUD_OPERATION_TEST_BRIDGE,
    nodeEnv: process.env.NODE_ENV || "",
    visibleAnnouncementRows,
    writeDb,
    workspaceChatSessionsForUser,
  });

  return {
    ...portalApiPayloads,
    handlePortalAdminApiRoutes,
    handlePortalApiRoutes,
  };
}
