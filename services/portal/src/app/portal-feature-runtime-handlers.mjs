import { createOplRoutes } from "../routes/opl.routes.mjs";
import { createLabPackageRoutes } from "../routes/lab-package.routes.mjs";
import { createResourceOrderRoutes } from "../routes/resource-order.routes.mjs";
import { createWorkspaceFilesInternalRoutes } from "../routes/workspace-files-internal.routes.mjs";
import { createWorkspaceStorageRoutes } from "../routes/workspace-storage.routes.mjs";

export function createPortalFeatureRuntimeHandlers({
  appendCookie,
  buildWorkspaceFileChecksum,
  buildWorkspaceStorageKey,
  createOrUpdateStorageOrder,
  defaultTaskTitle,
  ensureTaskSpace,
  exists,
  fetchServerPlans,
  fetchWorkspaceUserStorageState,
  fetchWorkspaceStorageSnapshot,
  findTaskSpace,
  guessContentType,
  issueWorkspaceTransferToken,
  layoutV2,
  listWorkspaceFiles,
  logPortalEvent,
  markWorkspaceStorageDeleting,
  mkdir,
  normalizeAuthEmail,
  oplLaunchService,
  path,
  portalInternalAuthAllowed,
  productRuntimeMode = "platform_provisioned",
  readBody,
  readDb,
  readJsonBody,
  readWorkspaceTransferToken,
  recordWorkspaceFile,
  safeRelativePath,
  sendFile,
  sendHtml,
  sendJson,
  slugify,
  stat,
  syncWorkspaceFileToUserStorage,
  workspaceSessionCookie,
  workspaceStorageEntitlement,
  writeFile,
  writeDb,
}) {
  const handleLabPackageRoutes = createLabPackageRoutes({
    readBody,
    sendJson,
    writeDb,
  });
  const handleOplRoutes = createOplRoutes({
    appendCookie,
    layoutV2,
    logPortalEvent,
    oplLaunchService,
    readBody,
    sendHtml,
    sendJson,
    slugify,
    workspaceSessionCookie,
  });
  const handleWorkspaceStorageRoutes = createWorkspaceStorageRoutes({
    buildWorkspaceFileChecksum,
    buildWorkspaceStorageKey,
    createOrUpdateStorageOrder,
    defaultTaskTitle,
    ensureTaskSpace,
    exists,
    fetchWorkspaceUserStorageState,
    fetchWorkspaceStorageSnapshot,
    findTaskSpace,
    guessContentType,
    issueWorkspaceTransferToken,
    listWorkspaceFiles,
    logPortalEvent,
    mkdir,
    path,
    readBody,
    readDb,
    readWorkspaceTransferToken,
    recordWorkspaceFile,
    safeRelativePath,
    sendFile,
    sendJson,
    slugify,
    stat,
    syncWorkspaceFileToUserStorage,
    workspaceStorageEntitlement,
    writeFile,
    writeDb,
  });
  const handleWorkspaceFilesInternalRoutes = createWorkspaceFilesInternalRoutes({
    defaultTaskTitle,
    ensureTaskSpace,
    findTaskSpace,
    logPortalEvent,
    portalInternalAuthAllowed,
    readBody,
    recordWorkspaceFile,
    safeRelativePath,
    sendJson,
    writeDb,
  });
  const handleResourceOrderRoutes = createResourceOrderRoutes({
    defaultTaskTitle,
    ensureTaskSpace,
    fetchServerPlans,
    logPortalEvent,
    markWorkspaceStorageDeleting,
    normalizeAuthEmail,
    portalInternalAuthAllowed,
    productRuntimeMode,
    readJsonBody,
    sendJson,
    slugify,
    writeDb,
  });

  return {
    handleLabPackageRoutes,
    handleOplRoutes,
    handleWorkspaceFilesInternalRoutes,
    handleResourceOrderRoutes,
    handleWorkspaceStorageRoutes,
  };
}
