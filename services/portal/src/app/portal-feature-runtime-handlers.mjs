import { createOplRoutes } from "../routes/opl.routes.mjs";
import { createResourceOrderRoutes } from "../routes/resource-order.routes.mjs";
import { createWorkspaceStorageRoutes } from "../routes/workspace-storage.routes.mjs";

export function createPortalFeatureRuntimeHandlers({
  appendCookie,
  buildWorkspaceFileChecksum,
  buildWorkspaceStorageKey,
  createOrUpdateStorageOrder,
  defaultTaskTitle,
  ensureTaskSpace,
  exists,
  fetchServerPlans,
  fetchWorkspaceMinioState,
  fetchWorkspaceStorageSnapshot,
  findTaskSpace,
  guessContentType,
  issueWorkspaceTransferToken,
  layoutV2,
  listWorkspaceFiles,
  logPortalEvent,
  mkdir,
  normalizeAuthEmail,
  oplLaunchService,
  path,
  portalInternalAuthAllowed,
  readBody,
  readDb,
  readJsonBody,
  readWorkspaceTransferToken,
  recordWorkspaceFile,
  resourceProvisionerClient,
  safeRelativePath,
  sendFile,
  sendHtml,
  sendJson,
  slugify,
  stat,
  syncWorkspaceFileToMinio,
  workspaceSessionCookie,
  workspaceStorageEntitlement,
  writeFile,
  writeDb,
}) {
  const handleOplRoutes = createOplRoutes({
    appendCookie,
    layoutV2,
    oplLaunchService,
    readBody,
    sendHtml,
    sendJson,
    slugify,
    workspaceSessionCookie,
  });
  const handleWorkspaceStorageRoutes = createWorkspaceStorageRoutes({
    buildWorkspaceFileChecksum,
    buildWorkspaceStorageKey,
    createOrUpdateStorageOrder,
    defaultTaskTitle,
    ensureTaskSpace,
    exists,
    fetchWorkspaceMinioState,
    fetchWorkspaceStorageSnapshot,
    findTaskSpace,
    guessContentType,
    issueWorkspaceTransferToken,
    listWorkspaceFiles,
    logPortalEvent,
    mkdir,
    path,
    readBody,
    readDb,
    readWorkspaceTransferToken,
    recordWorkspaceFile,
    safeRelativePath,
    sendFile,
    sendJson,
    slugify,
    stat,
    syncWorkspaceFileToMinio,
    workspaceStorageEntitlement,
    writeFile,
    writeDb,
  });
  const handleResourceOrderRoutes = createResourceOrderRoutes({
    defaultTaskTitle,
    ensureTaskSpace,
    fetchServerPlans,
    logPortalEvent,
    normalizeAuthEmail,
    portalInternalAuthAllowed,
    readJsonBody,
    resourceProvisionerClient,
    sendJson,
    slugify,
    writeDb,
  });

  return {
    handleOplRoutes,
    handleResourceOrderRoutes,
    handleWorkspaceStorageRoutes,
  };
}
