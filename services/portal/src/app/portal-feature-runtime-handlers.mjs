import { createOplRoutes } from "../routes/opl.routes.mjs";
import { createLabPackageRoutes } from "../routes/lab-package.routes.mjs";
import { createWorkspaceFilesInternalRoutes } from "../routes/workspace-files-internal.routes.mjs";
import { createWorkspaceStorageRoutes } from "../routes/workspace-storage.routes.mjs";

export function createPortalFeatureRuntimeHandlers({
  appendCookie,
  buildWorkspaceFileChecksum,
  buildWorkspaceStorageKey,
  createOrUpdateStorageOrder,
  defaultTaskTitle,
  ensureTaskSpace,
  exists,
  fetchServerPlans,
  fetchWorkspaceUserStorageState,
  fetchWorkspaceStorageSnapshot,
  findTaskSpace,
  guessContentType,
  issueWorkspaceTransferToken,
  layoutV2,
  listWorkspaceFiles,
  logPortalEvent,
  markWorkspaceStorageDeleting,
  mkdir,
  normalizeAuthEmail,
  runtimeBridgeClient,
  oplLaunchService,
  path,
  portalInternalAuthAllowed,
  portalConfig = {},
  productRuntimeMode = "platform_provisioned",
  readBody,
  readDb,
  readJsonBody,
  readWorkspaceTransferToken,
  recordWorkspaceFile,
  safeRelativePath,
  sendFile,
  sendHtml,
  sendJson,
  slugify,
  stat,
  syncWorkspaceFileToUserStorage,
  workspaceSessionCookie,
  workspaceStorageEntitlement,
  writeFile,
  writeDb,
}) {
  const handleLabPackageRoutes = createLabPackageRoutes({
    readBody,
    sendJson,
    writeDb,
    enableCloudOperationProductionBridge: portalConfig?.PORTAL_ENABLE_CLOUD_OPERATION_PRODUCTION_BRIDGE,
    cloudOperationRunnerMode: portalConfig?.PORTAL_CLOUD_OPERATION_RUNNER_MODE,
    cloudOperationRunnerScript: portalConfig?.PORTAL_CLOUD_OPERATION_RUNNER_SCRIPT,
    cloudOperationSecretFile: portalConfig?.PORTAL_CLOUD_OPERATION_PACKAGE_C_SECRET_FILE,
    cloudOperationComputeNodePoolRef: portalConfig?.PORTAL_CLOUD_OPERATION_COMPUTE_NODE_POOL_REF,
    cloudOperationComputePoolBaselineCapacity: portalConfig?.PORTAL_CLOUD_OPERATION_COMPUTE_POOL_BASELINE_CAPACITY,
    repoRoot: process.cwd().endsWith("/services/portal") ? "../.." : ".",
  });
  const handleOplRoutes = createOplRoutes({
    appendCookie,
    layoutV2,
    logPortalEvent,
    runtimeBridgeClient,
    oplLaunchService,
    readBody,
    sendHtml,
    sendJson,
    slugify,
    workspaceSessionCookie,
  });
  const handleWorkspaceStorageRoutes = createWorkspaceStorageRoutes({
    buildWorkspaceFileChecksum,
    buildWorkspaceStorageKey,
    createOrUpdateStorageOrder,
    defaultTaskTitle,
    ensureTaskSpace,
    exists,
    fetchWorkspaceUserStorageState,
    fetchWorkspaceStorageSnapshot,
    findTaskSpace,
    guessContentType,
    issueWorkspaceTransferToken,
    listWorkspaceFiles,
    logPortalEvent,
    mkdir,
    path,
    readBody,
    readDb,
    readWorkspaceTransferToken,
    recordWorkspaceFile,
    safeRelativePath,
    sendFile,
    sendJson,
    slugify,
    stat,
    syncWorkspaceFileToUserStorage,
    workspaceStorageEntitlement,
    writeFile,
    writeDb,
  });
  const handleWorkspaceFilesInternalRoutes = createWorkspaceFilesInternalRoutes({
    defaultTaskTitle,
    ensureTaskSpace,
    findTaskSpace,
    logPortalEvent,
    portalInternalAuthAllowed,
    readBody,
    recordWorkspaceFile,
    safeRelativePath,
    sendJson,
    writeDb,
  });
  return {
    handleLabPackageRoutes,
    handleOplRoutes,
    handleWorkspaceFilesInternalRoutes,
    handleWorkspaceStorageRoutes,
  };
}
